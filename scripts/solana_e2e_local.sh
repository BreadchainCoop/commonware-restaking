    if [[ "$LLM_MODEL" == "qwen" ]]; then
        ok "SOLANA QWEN SETTLEMENT E2E PASSED — the real Qwen3-0.6B answer was certified by the 4-operator BLS committee and settled on-chain (digest $LLM_NEW_DIGEST)"
